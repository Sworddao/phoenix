private fun tonesOf(pinyin: String): List<Int> {
    return pinyin
        .split(Regex("\\s+"))
        .filter { it.isNotEmpty() }
        .map { syllable ->
            var tone = 0
            for (char in syllable) {
                tone = when (char) {
                    in "\u0101\u0113\u012B\u014D\u016B\u01D6" -> 1
                    in "\u00E1\u00E9\u00ED\u00F3\u00FA\u01D8" -> 2
                    in "\u01CE\u011B\u01D0\u01D4\u01DA" -> 3
                    in "\u00E0\u00E8\u00EC\u00F2\u00F9\u01DC" -> 4
                    else -> continue
                }
                break
            }
            tone
        }
}

